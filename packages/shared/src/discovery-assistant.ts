import { z } from "zod";
import {
  ContentGpsQuerySchema,
  ContentGpsSearchCardSchema,
  ContentGpsSearchRequestSchema,
} from "./content-gps.js";
import {
  CreatorDiscoveryQuerySchema,
  CreatorDiscoveryCardSchema,
  CreatorDiscoveryRequestSchema,
} from "./creator-location.js";

export const DiscoveryConversationSchema = z
  .strictObject({
    messages: z
      .array(
        z.strictObject({
          role: z.enum(["user", "assistant"]),
          content: z.string().trim().min(1).max(2000),
        })
      )
      .min(1)
      .max(12),
    current: z.discriminatedUnion("kind", [
      z.strictObject({
        kind: z.literal("ips"),
        query: ContentGpsQuerySchema.omit({ locale: true }),
      }),
      z.strictObject({ kind: z.literal("creators"), query: CreatorDiscoveryQuerySchema }),
    ]),
  })
  .refine((v) => v.messages.at(-1)?.role === "user", "The last turn must be a user message")
  .refine(
    (v) => v.messages.reduce((n, m) => n + m.content.length, 0) <= 16000,
    "Conversation is too long"
  );
export const DiscoveryAssistantRequestSchema = z.strictObject({
  requestId: z.uuid(),
  locale: ContentGpsQuerySchema.shape.locale,
  conversation: DiscoveryConversationSchema,
});
const counts = {
  status: z.literal("results"),
  queryId: z.string().regex(/^[a-f0-9]{64}$/),
  matchedCount: z.number().int().nonnegative().safe(),
  accessibleCount: z.number().int().nonnegative().safe(),
};
export const DiscoveryAssistantResultSchema = z
  .union([
    z.strictObject({
      status: z.literal("clarification"),
      question: z.string().trim().min(1).max(1000),
    }),
    z.strictObject({
      ...counts,
      kind: z.literal("ips"),
      query: ContentGpsQuerySchema,
      cards: z.array(ContentGpsSearchCardSchema).max(5),
      countScope: z.literal("accessible_ips_with_published_translation"),
    }),
    z.strictObject({
      ...counts,
      kind: z.literal("creators"),
      query: CreatorDiscoveryQuerySchema,
      cards: z.array(CreatorDiscoveryCardSchema).max(5),
      requiresLogin: z.boolean(),
      countScope: z.literal("public_platform_creators_with_listed_services"),
    }),
  ])
  .superRefine((v, ctx) => {
    if (v.status !== "results") return;
    if (
      v.matchedCount > v.accessibleCount ||
      v.cards.some((card) => !card.matched) ||
      new Set(v.cards.map((card) => card.id)).size !== v.cards.length ||
      v.cards.length > v.matchedCount ||
      (v.matchedCount > 0 && v.cards.length === 0)
    )
      ctx.addIssue({
        code: "custom",
        message: "Recommendations must be distinct matching catalogue cards",
      });
  });
// Internal only: scoped opaque credential is generated by the authenticated
// admission service and never placed in model context or public responses.
export const DiscoveryReadCredentialSchema = z.strictObject({
  requestId: z.uuid(),
  readToken: z.string().regex(/^[a-f0-9]{64}$/),
});
export const DiscoveryWorkerRequestSchema = DiscoveryAssistantRequestSchema.extend({
  credential: DiscoveryReadCredentialSchema,
  coordinateSystem: z.enum(["WGS84", "GCJ02"]),
  genres: z
    .array(
      z.strictObject({
        code: z.string().trim().min(1).max(200),
        label: z.string().trim().min(1).max(300),
      })
    )
    .max(500),
}).refine((v) => v.requestId === v.credential.requestId, "Mismatched discovery request identity");
export const DiscoveryReadRequestSchema = z.discriminatedUnion("kind", [
  DiscoveryReadCredentialSchema.extend({
    kind: z.literal("ips"),
    input: ContentGpsSearchRequestSchema,
  }),
  DiscoveryReadCredentialSchema.extend({
    kind: z.literal("creators"),
    input: CreatorDiscoveryRequestSchema,
  }),
]);
export type DiscoveryAssistantResult = z.infer<typeof DiscoveryAssistantResultSchema>;
export type DiscoveryAssistantRequest = z.infer<typeof DiscoveryAssistantRequestSchema>;

export const DiscoveryAssistantReceiptSchema = z
  .strictObject({
    requestId: z.uuid(),
    status: z.enum(["dispatched", "succeeded", "uncertain", "cancelled"]),
    result: DiscoveryAssistantResultSchema.nullable(),
  })
  .refine(
    (v) => (v.status === "succeeded") === (v.result !== null),
    "Invalid discovery receipt state"
  );
export type DiscoveryAssistantReceipt = z.infer<typeof DiscoveryAssistantReceiptSchema>;
