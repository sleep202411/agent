/**
 * Event outbox — durable Web PubSub fan-out.
 *
 * Why: a fire-and-forget `publishAssetEvent` call vanishes if the
 * Web PubSub service has a hiccup, leaving the browser permanently
 * out of sync. The outbox records every emit attempt in Postgres so
 * a background dispatcher can retry until publish actually lands.
 *
 * Happy-path flow:
 *   1. record(job)        — INSERT outbox row + try publish in same tick
 *   2. publish succeeds   — mark dispatchedAt
 *   3. publish fails      — leave dispatchedAt NULL; dispatcher loop
 *                            retries every DISPATCH_INTERVAL_MS
 *
 * Production hardening would also: cap retry count → DLQ table,
 * paginate the dispatcher query, run dispatcher in a separate pod.
 */
import {
  Injectable,
  Logger,
  type OnApplicationBootstrap,
  type OnModuleDestroy,
} from '@nestjs/common';
import { Prisma } from '@prisma/client';
import { PrismaService } from '../infra/db/db.module';
import { WebPubSubService } from '../infra/realtime/web-pubsub.service';
import { toAiJobEvent } from './job-event';
import type { AiJob } from './types';

const DISPATCH_INTERVAL_MS = 5_000;
const DISPATCH_BATCH = 25;
// Drop events older than this without further attempts. Stale enough
// that no UI cares; the DB row stays for audit.
const DEAD_EVENT_AGE_MS = 24 * 60 * 60 * 1000;
const GC_OLDER_THAN_MS = 7 * 24 * 60 * 60 * 1000;

@Injectable()
export class AiGenerationOutboxService
  implements OnApplicationBootstrap, OnModuleDestroy
{
  private readonly logger = new Logger(AiGenerationOutboxService.name);
  private timer: NodeJS.Timeout | null = null;
  private draining = false;

  constructor(
    private readonly prisma: PrismaService,
    private readonly webPubSub: WebPubSubService,
  ) {}

  /**
   * Insert an outbox row for this job's current state and try to
   * publish in the same tick. A given (job, state) may produce
   * multiple rows over time — clients dedupe by `job.updatedAt` on
   * the receive side.
   */
  async record(job: AiJob): Promise<void> {
    const event = toAiJobEvent(job);
    // ID is generated by Prisma `@default(uuid())`. We need it back
    // for the optimistic publish + dispatcher updates, so capture
    // the created row.
    const row = await this.prisma.aiEventOutbox.create({
      data: {
        jobId: job.id,
        userId: job.userId,
        payload: event as unknown as Prisma.InputJsonValue,
        attempt: 0,
      },
    });
    // Optimistic publish — don't await, don't fail the caller if
    // Web PubSub is down. Dispatcher cleans up.
    void this.tryDispatch(row.id, job.userId, event);
  }

  onApplicationBootstrap(): void {
    this.timer = setInterval(() => void this.drainOnce(), DISPATCH_INTERVAL_MS);
    this.logger.log(
      `Outbox dispatcher running every ${DISPATCH_INTERVAL_MS}ms`,
    );
  }

  onModuleDestroy(): void {
    if (this.timer) {
      clearInterval(this.timer);
      this.timer = null;
    }
  }

  private async drainOnce(): Promise<void> {
    if (this.draining) return; // overlap guard
    this.draining = true;
    try {
      const cutoff = new Date(Date.now() - DEAD_EVENT_AGE_MS);
      const rows = await this.prisma.aiEventOutbox.findMany({
        where: {
          dispatchedAt: null,
          createdAt: { gt: cutoff },
        },
        orderBy: { createdAt: 'asc' },
        take: DISPATCH_BATCH,
      });

      for (const row of rows) {
        const payload = row.payload as unknown as Parameters<
          WebPubSubService['publishAssetEvent']
        >[1];
        try {
          await this.webPubSub.publishAssetEvent(row.userId, payload);
          await this.prisma.aiEventOutbox.update({
            where: { id: row.id },
            data: { dispatchedAt: new Date(), attempt: row.attempt + 1 },
          });
        } catch (err) {
          await this.prisma.aiEventOutbox.update({
            where: { id: row.id },
            data: { attempt: row.attempt + 1 },
          });
          this.logger.warn(
            `outbox dispatch failed id=${row.id}: ${err instanceof Error ? err.message : String(err)}`,
          );
        }
      }

      // Best-effort GC: drop very old dispatched rows so the table
      // doesn't grow without bound. Keep 7 days for forensics.
      await this.prisma.aiEventOutbox.deleteMany({
        where: {
          dispatchedAt: { lt: new Date(Date.now() - GC_OLDER_THAN_MS) },
        },
      });
    } catch (err) {
      this.logger.warn(
        `outbox drain failed: ${err instanceof Error ? err.message : String(err)}`,
      );
    } finally {
      this.draining = false;
    }
  }

  private async tryDispatch(
    rowId: string,
    userId: string,
    payload: ReturnType<typeof toAiJobEvent>,
  ): Promise<void> {
    try {
      await this.webPubSub.publishAssetEvent(userId, payload);
      await this.prisma.aiEventOutbox.update({
        where: { id: rowId },
        data: { dispatchedAt: new Date(), attempt: 1 },
      });
    } catch {
      // Dispatcher loop will pick it up.
    }
  }
}
